#!/usr/bin/env python3
"""Write the unknowns register from every page's `Unverified` section.

A page's `Unverified` section is the only place an open claim is written down.
The register is an index of those claims, grouped by tier, so a reader can see
where the map is thin without opening every page.

Nothing here is a second copy. Each row is the claim cut to an index line, and
a link to the page that holds it in full and in context — so when a claim is
settled, it is deleted from the page and the register regenerates without it.

    python3 scripts/collect_unknowns.py            # rewrite the register
    python3 scripts/collect_unknowns.py --check    # fail if the register is stale

A generated page is never edited by hand: `check_structure.py` runs the
`--check` pass, so a page edited without regenerating fails the build rather
than drifting. The register's growth is a failure; that is the point of it.

Where the register lives, and which sections and tiers a page has, are in
`map.json` — see `map_config.py`.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

import map_config as config

ROOT = config.ROOT
OUT = ROOT / config.get("unknowns")
UNVERIFIED = "## " + config.get("sections")[-1]
TIERS = config.get_tiers()
BULLET = "- "
LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")
SETTLE = re.compile(
    r"\bSettle(?:[A-Za-z ]{0,40})?:\s*"          # Settle: …  /  Settle the question: …
    r"|\bSettle(?:\s+(?:it|this|that))?\s+(?:with|by|in|via)\s+"  # Settle it by reading …
    r"|\bsettled by\s+",
    re.IGNORECASE,
)
CLAIM_CHARS = 150
HEADER = """<!-- generated by scripts/collect_unknowns.py — do not edit -->

# Unknowns: {tier}

A generated index of every claim marked `{section}` on a page filed under `{tier}/` — {n} of them. This page is written by `scripts/collect_unknowns.py`; the claim lives on the page linked in the first column, in full and in context, and settling it means editing that page rather than this one.

A row's third column is the bullet's own `Settle:` clause where it has one, and `—` where it does not: an open claim with no stated way to close it is the worse kind, and it is worth reading as a warning.

| Page | The open claim | How to settle it |
| --- | --- | --- |
"""


def pages() -> list[Path]:
    """Every page that can carry an open claim — the register itself is not one."""
    kept: list[Path] = []
    for page in config.pages():
        try:
            page.resolve().relative_to(OUT.resolve())
            continue
        except ValueError:
            kept.append(page)
    return kept


def label(page: Path) -> str:
    """The page's name as a reader would say it: its folder, if it is an index."""
    if page.stem == "README":
        return "%s (index)" % page.parent.name
    return page.stem.replace("-", " ")


def cell(text: str) -> str:
    """One table cell: no pipe, no newline, and short enough to skim."""
    text = LINK.sub(r"\1", text)
    text = text.replace("**", "").replace("|", "\\|").strip()
    if len(text) > CLAIM_CHARS:
        cut = text[:CLAIM_CHARS].rsplit(" ", 1)[0]
        text = cut + "…"
    return text


def open_claims(page: Path) -> list[tuple[str, str]]:
    """The (claim, settle) pairs a page holds, in the order it holds them."""
    lines = page.read_text(encoding="utf-8").splitlines()
    if UNVERIFIED not in lines:
        return []
    claims: list[tuple[str, str]] = []
    for line in lines[lines.index(UNVERIFIED) + 1:]:
        if not line.startswith(BULLET):
            continue
        body = line[len(BULLET):]
        found = SETTLE.search(body)
        settle = cell(LINK.sub(r"\1", body[found.end():])) if found else "—"
        claims.append((cell(body[: found.start()] if found else body), settle))
    return claims


def link_to(page: Path) -> str:
    """The page's path as seen from a file inside the register."""
    return os.path.relpath(str(page), str(OUT)).replace(os.sep, "/")


def render() -> dict[Path, str]:
    """Every file the register is made of, keyed by path."""
    tiers = list(TIERS)
    grouped: dict[str, list[tuple[Path, list[tuple[str, str]]]]] = {tier: [] for tier in tiers}
    for page in pages():
        claims = open_claims(page)
        if not claims:
            continue
        tier = config.tier_of(page)
        if tier not in grouped:
            grouped[tier] = []
            tiers.append(tier)
        grouped[tier].append((page, claims))

    written: dict[Path, str] = {}
    counts: list[tuple[str, int, int]] = []
    for tier in [name for name in tiers if grouped.get(name)]:
        entries = grouped[tier]
        total = sum(len(claims) for _, claims in entries)
        counts.append((tier, len(entries), total))
        body = HEADER.format(
            tier=tier, n=total, section=config.get("sections")[-1]
        ).rstrip("\n").split("\n")
        for page, claims in entries:
            for claim, settle in claims:
                body.append(f"| [{label(page)}]({link_to(page)}) | {claim} | {settle} |")
        written[OUT / f"{tier}.md"] = "\n".join(body) + "\n"

    index = [
        "<!-- generated by scripts/collect_unknowns.py — do not edit -->",
        "",
        "# The unknowns register",
        "",
        "Every claim in this map marked `%s`, grouped by the tier of the page that "
        "holds it. The claim itself lives on that page; this folder only counts them and "
        "points at them, so it cannot disagree with them." % config.get("sections")[-1],
        "",
        "This is the one part of the map whose growth is a failure. A tier with many rows is "
        "a tier nobody has run; a row with no `Settle:` clause is a claim nobody has worked "
        "out how to close.",
        "",
        "| Tier | Pages holding an open claim | Open claims |",
        "| --- | --- | --- |",
    ]
    for tier, holders, total in counts:
        index.append(f"| [{tier}]({tier}.md) | {holders} | {total} |")
    index.append(f"| **all** | **{sum(h for _, h, _ in counts)}** | "
                 f"**{sum(n for _, _, n in counts)}** |")
    written[OUT / "README.md"] = "\n".join(index) + "\n"
    return written


def main() -> int:
    written = render()
    where = config.get("unknowns")
    if "--check" in sys.argv[1:]:
        stale = [
            path
            for path, text in written.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(f"STALE {config.relative(path)} — run python3 scripts/collect_unknowns.py")
        for path in sorted(OUT.glob("*.md")) if OUT.exists() else []:
            if path not in written:
                print(f"STALE {config.relative(path)} — generated for a tier that has none left")
        return 1 if stale else 0

    OUT.mkdir(parents=True, exist_ok=True)
    for path in OUT.glob("*.md"):
        if path not in written:
            path.unlink()
    for path, text in written.items():
        path.write_text(text, encoding="utf-8")
    total = sum(len(open_claims(page)) for page in pages())
    print(f"{len(written) - 1} tiers, {total} open claims, written to {where}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
